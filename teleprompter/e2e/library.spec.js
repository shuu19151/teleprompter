import { expect, test } from '@playwright/test'
import { prepareLibrary } from './library-fixture.js'

test('one library supports import, duplicate detection, edit, delete and folder switching', async ({ page }, testInfo) => {
  await prepareLibrary(page)
  await page.goto('/')
  await expect(page.locator('#imports-label')).toHaveText('Texts')
  await expect(page.locator('#essay-list')).toHaveCount(0)
  const initial = await page.locator('#import-list .essay').count()
  expect(initial).toBeGreaterThan(0)
  async function add(body) {
    await page.locator('#import-open').click()
    await page.locator('#import-body').fill(body)
    await page.locator('#import-save').click()
    await expect(page.locator('#import-dialog')).not.toBeVisible()
  }
  await add('Library Test\n\nOriginal body')
  await expect(page.locator('#import-list .essay')).toHaveCount(initial + 1)
  await add('Library Test\n\nOriginal body')
  await expect(page.locator('#import-list .essay')).toHaveCount(initial + 1)
  await add('Library Test\n\nDifferent body')
  await expect(page.locator('#import-list .essay')).toHaveCount(initial + 2)
  await page.locator('#import-list .essay.is-on').click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Edit', exact: true }).click()
  await page.locator('#import-name').fill('Edited text')
  await page.locator('#import-body').fill('Edited body')
  await page.locator('#import-save').click()
  await expect(page.locator('#import-dialog')).not.toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Edited text')
  await expect(page.locator('#text-script')).toContainText('Edited body')
  await page.locator('#import-list .essay.is-on').click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
  await page.getByRole('dialog', { name: 'Delete text?' }).getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.locator('#import-list .essay')).toHaveCount(initial + 1)
  await page.locator('#sidebar').screenshot({ path: testInfo.outputPath('texts-sidebar.png') })
  await page.evaluate(() => {
    window.showDirectoryPicker = async () => (await navigator.storage.getDirectory()).getDirectoryHandle('Other library', { create: true })
  })
  await page.locator('#choose-folder').click()
  await expect(page.locator('#folder-name')).toHaveText('Other library')
  await expect(page.locator('#import-list .essay')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('#folder-name')).toHaveText('Other library')
  await expect(page.locator('#import-list .essay')).toHaveCount(0)
})

test('new installation explains how to choose a library', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('#import-list')).toContainText('Choose a library folder')
  await expect(page.locator('#reload')).toBeDisabled()
  await page.locator('#import-open').click()
  await page.locator('#import-body').fill('New text\n\nBody')
  await page.locator('#import-save').click()
  await expect(page.locator('#import-error')).toHaveText('Choose a library folder first.')
})
